// Generates desktop/style.css and web/style.css from shared/palettes.mjs,
// and page/style.css + widget/style.css from their base.css + shared/usage.css.
//
// Both hosts receive the same palette tokens (--pf-*). Only the marker
// attribute prefix and the host token mapping differ:
//   Desktop: api.dom.mark → data-cx-<id>-<name>      (Codex Desktop tokens)
//   Web:     api.dom.mark → data-cx-ext-<id>-<name>  (CH Web --dsw-* tokens)

import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import {
  ACCENTS,
  CODE_FONTS,
  EXTENSION_ID,
  PALETTES,
} from "../shared/palettes.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const HEADER = `/*
 * Prism Facets — generated by tools/build-css.mjs. Do not edit by hand.
 * SPDX-License-Identifier: GPL-3.0-only
 * Palette values ported from Obsidian Prism (c) 2026 RMvdesi,
 * https://github.com/RMvdesi/obsidian-prism — modified 2026-11-26 for codexhost.
 */
`;

function hostCss(host) {
  const prefix = host === "desktop" ? `data-cx-${EXTENSION_ID}-` : `data-cx-ext-${EXTENSION_ID}-`;
  const m = (name) => `[${prefix}${name}]`;
  const on = `html${m("on")}`;
  const out = [HEADER];

  // 1. Palette tokens.
  for (const [id, p] of Object.entries(PALETTES)) {
    out.push(`${on}${m(`p-${id}`)} {
  color-scheme: ${p.scheme} !important;
  --pf-bg: ${p.bg};
  --pf-sidebar: ${p.sidebar};
  --pf-card: ${p.card};
  --pf-secondary: ${p.secondary};
  --pf-muted: ${p.muted};
  --pf-raised: ${p.raised};
  --pf-code-bg: ${p.codeBg};
  --pf-fg: ${p.fg};
  --pf-fg2: ${p.fg2};
  --pf-fg3: ${p.fg3};
  --pf-placeholder: ${p.placeholder};
  --pf-accent: ${p.accent};
  --pf-on-accent: ${p.onAccent};
  --pf-link: ${p.link};
  --pf-error: ${p.error};
  --pf-warning: ${p.warning};
  --pf-success: ${p.success};
  --pf-border: ${p.border};
  --pf-card-border: ${p.cardBorder};
  --pf-menu: ${p.menu};
  --pf-menu-border: ${p.menuBorder};
  --pf-popover: ${p.popover};
  --pf-bubble: ${p.bubble};
  --pf-scrim: ${p.scrim};
  --pf-specular: ${p.specular};
  --pf-spec-1: ${p.spectrum[0]};
  --pf-spec-2: ${p.spectrum[1]};
  --pf-spec-3: ${p.spectrum[2]};
  --pf-spec-4: ${p.spectrum[3]};
}
`);
  }

  // 2. Accent tones (per scheme), overriding the palette accent.
  for (const [id, tones] of Object.entries(ACCENTS)) {
    for (const scheme of ["dark", "light"]) {
      const t = tones[scheme];
      out.push(`${on}${m(`s-${scheme}`)}${m(`a-${id}`)} {
  --pf-accent: ${t.accent};
  --pf-link: ${t.link};
  --pf-on-accent: ${t.onAccent};
  --pf-spec-1: ${t.spectrum[0]};
  --pf-spec-2: ${t.spectrum[1]};
  --pf-spec-3: ${t.spectrum[2]};
  --pf-spec-4: ${t.spectrum[3]};
}
`);
    }
  }

  // 3. Derived tokens shared by both hosts.
  out.push(`${on} {
  --pf-wash: color-mix(in srgb, var(--pf-fg) 4%, transparent);
  --pf-hover: color-mix(in srgb, var(--pf-fg) 6%, transparent);
  --pf-pressed: color-mix(in srgb, var(--pf-fg) 10%, transparent);
  --pf-accent-soft: color-mix(in srgb, var(--pf-accent) 16%, var(--pf-bg));
  --pf-accent-soft-hover: color-mix(in srgb, var(--pf-accent) 21%, var(--pf-bg));
  --pf-accent-soft-active: color-mix(in srgb, var(--pf-accent) 27%, var(--pf-bg));
  --pf-accent-hover: color-mix(in srgb, var(--pf-accent) 88%, var(--pf-fg));
  --pf-accent-active: color-mix(in srgb, var(--pf-accent) 78%, var(--pf-fg));
  --pf-selection: color-mix(in srgb, var(--pf-accent) 28%, transparent);
  --pf-ring: color-mix(in srgb, var(--pf-accent) 55%, transparent);
}
`);

  // 4. Host token mapping.
  out.push(host === "desktop" ? desktopMapping(on) : webMapping(on));

  // 5. Corners.
  out.push(host === "desktop" ? desktopCorners(on, m) : webCorners(on, m));

  // 6. Code fonts and ligatures.
  for (const [id, stack] of Object.entries(CODE_FONTS)) {
    if (!stack) continue;
    out.push(
      host === "desktop"
        ? `${on}${m(`f-${id}`)} {\n  --font-code-family: ${stack} !important;\n  --font-mono: ${stack} !important;\n}\n`
        : `${on}${m(`f-${id}`)} {\n  --ds-font-family-code: ${stack} !important;\n}\n`,
    );
  }
  out.push(`${on}${m("lig")} :is(code, pre, kbd, samp, .cm-content, .monaco-editor .view-lines) {
  font-variant-ligatures: contextual common-ligatures !important;
  font-feature-settings: "calt" 1, "liga" 1 !important;
}
`);

  // 7. Ambient prism light: a spectrum hairline plus a soft aura at the top of
  //    the window. Static (0 fps when idle) and never takes pointer input.
  //    Each level changes line thickness, glow and aura height/strength so the
  //    steps are clearly distinguishable.
  const AMBIENT_STYLE = {
    low: { line: "1px", lineO: 0.4, glow: "4px", auraH: "90px", auraO: 0.05 },
    medium: { line: "1.5px", lineO: 0.6, glow: "8px", auraH: "150px", auraO: 0.09 },
    high: { line: "2px", lineO: 0.8, glow: "12px", auraH: "220px", auraO: 0.15 },
  };
  for (const [level, v] of Object.entries(AMBIENT_STYLE)) {
    out.push(`${on}${m(`amb-${level}`)} {
  --pf-amb-line: ${v.line};
  --pf-amb-line-o: ${v.lineO};
  --pf-amb-glow: ${v.glow};
  --pf-amb-aura-h: ${v.auraH};
  --pf-amb-aura-o: ${v.auraO};
}
`);
  }
  const ambLevels = Object.keys(AMBIENT_STYLE).map((k) => m(`amb-${k}`)).join(", ");
  const amb = `${on}:is(${ambLevels})`;
  out.push(`${amb} body::after {
  content: "";
  position: fixed;
  inset: 0 0 auto 0;
  height: var(--pf-amb-line);
  z-index: 2147483000;
  pointer-events: none;
  background: linear-gradient(90deg, transparent 0%, var(--pf-spec-1) 14%, var(--pf-spec-2) 40%, var(--pf-spec-3) 66%, var(--pf-spec-4) 88%, transparent 100%);
  opacity: var(--pf-amb-line-o);
  box-shadow:
    0 0 var(--pf-amb-glow) 0 color-mix(in srgb, var(--pf-spec-2) 55%, transparent),
    0 0 calc(var(--pf-amb-glow) * 2) 0 color-mix(in srgb, var(--pf-spec-1) 25%, transparent);
}
${amb} body::before {
  content: "";
  position: fixed;
  inset: 0 0 auto 0;
  height: var(--pf-amb-aura-h);
  z-index: 2147482999;
  pointer-events: none;
  background:
    radial-gradient(55% 100% at 18% 0%, var(--pf-spec-1) 0%, transparent 72%),
    radial-gradient(45% 95% at 52% 0%, var(--pf-spec-2) 0%, transparent 70%),
    radial-gradient(40% 90% at 84% 0%, var(--pf-spec-3) 0%, transparent 70%);
  opacity: var(--pf-amb-aura-o);
  mix-blend-mode: screen;
}
${on}${m("s-light")}:is(${ambLevels}) body::before {
  mix-blend-mode: multiply;
  opacity: calc(var(--pf-amb-aura-o) * 0.55);
}
@media print {
  ${amb} body::before,
  ${amb} body::after { display: none; }
}
`);

  // 8. Frosted menus.
  out.push(`${on}${m("glass")} :is([role="menu"], [role="listbox"], [data-radix-popper-content-wrapper] > [role="dialog"]) {
  backdrop-filter: blur(16px) saturate(140%);
  -webkit-backdrop-filter: blur(16px) saturate(140%);
}
`);

  // 9. Selection & scrollbars.
  out.push(`${on} ::selection { background: var(--pf-selection); }
${on} ::-webkit-scrollbar-thumb:hover { background-color: color-mix(in srgb, var(--pf-fg) 28%, transparent); }
`);

  return out.join("\n");
}

function decl(entries) {
  return entries.map(([k, v]) => `  ${k}: ${v} !important;`).join("\n");
}

