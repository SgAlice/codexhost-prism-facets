async function emit(rel, css) {
  const target = join(root, rel);
  const previous = await readFile(target, "utf8").catch(() => "");
  if (previous !== css) await writeFile(target, css);
  console.log(`${rel.padEnd(18)} ${(Buffer.byteLength(css) / 1024).toFixed(1)} KiB`);
}

